export function juzRange(juz: number): { start: JuzRef; end: JuzRef } {
  const start = JUZ_START[juz - 1];
  const next = JUZ_START[juz];
  const end = next
    ? { number: juz, surah: next.surah, ayah: next.ayah - 1 }
    : { number: juz, surah: 114, ayah: 6 };
  return { start, end };
}

